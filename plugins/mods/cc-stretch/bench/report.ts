// Turns bench/out/*.jsonl into bench/results.md: aggregate numbers only, no reply text.
//   node bench/report.ts
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";

type Row = {
  source: "native" | "replay";
  project?: string;
  session?: string;
  turn?: number;
  original?: number;
  skim: number;
  full: number;
  read?: number;
  rewritten?: boolean;
  recall?: number;
};
type Graded = {
  project: string;
  version: "skim" | "original";
  points: number;
  yes: number;
  partly: number;
  verdicts?: string[];
};

const OUT = new URL("./out/", import.meta.url).pathname;
const rows: Row[] = (existsSync(OUT) ? readdirSync(OUT) : [])
  .filter((f) => f === "native.jsonl" || f === "replay.jsonl")
  .flatMap((f) =>
    readFileSync(OUT + f, "utf8")
      .split("\n")
      .filter(Boolean)
      .map((l) => JSON.parse(l) as Row),
  );

const sum = (xs: number[]) => xs.reduce((a, b) => a + b, 0);
const median = (xs: number[]) => {
  const s = [...xs].sort((a, b) => a - b);
  const at = (i: number) => s[i] ?? NaN;
  return s.length === 0
    ? NaN
    : s.length % 2
      ? at((s.length - 1) / 2)
      : (at(s.length / 2 - 1) + at(s.length / 2)) / 2;
};
const pct = (x: number) => `${Math.round(x * 100)}%`;
// Public outputs name projects by letter, in the order they first appear; real names stay in bench/out/.
const letters = new Map<string, string>();
const projectName = (dir = "") => {
  if (!letters.has(dir))
    letters.set(dir, `project ${String.fromCharCode(65 + letters.size)}`);
  return letters.get(dir) ?? dir;
};

const replay = rows.filter((r) => r.source === "replay");
const native = rows.filter((r) => r.source === "native");
const rewritten = replay.filter((r) => r.rewritten);
const noted = native.filter((r) => r.read !== undefined);
// With nothing measured, stop before the tracked results.md and results.csv are written over.
if (replay.length + native.length === 0) {
  console.error(
    "No measurements in bench/out/. Write some with bench/replay.ts or bench/native.ts first; bench/README.md has the commands.",
  );
  process.exit(1);
}

const lines: string[] = ["# cc-stretch benchmark results", ""];
lines.push(
  "Generated by `node bench/report.ts`. **skim**: a reply with every stretch closed. **full**: every stretch open. **read**: only the stretches the reader opened.",
  "",
);
if (replay.length > 0) {
  const projects = [...new Set(replay.map((r) => r.project))];
  lines.push(
    "## Replay: real replies from greenfield coding sessions, rewritten with the cc-stretch guide",
    "",
  );
  lines.push(
    "The comparison is with the reply as it was first written: what you would have read without cc-stretch.",
    "",
  );
  lines.push(
    "| project | replies | rewritten | original words | skim words | skim / original | median per reply | full / original |",
    "|---|---|---|---|---|---|---|---|",
  );
  for (const p of [...projects, undefined]) {
    const set =
      p === undefined ? replay : replay.filter((r) => r.project === p);
    const original = sum(set.map((r) => r.original ?? r.full));
    lines.push(
      `| ${p === undefined ? "**all**" : projectName(p)} | ${set.length} | ${set.filter((r) => r.rewritten).length} | ${original} | ${sum(set.map((r) => r.skim))} | **${pct(sum(set.map((r) => r.skim)) / original)}** | ${pct(median(set.map((r) => r.skim / (r.original ?? r.full))))} | ${pct(sum(set.map((r) => r.full)) / original)} |`,
    );
  }
  lines.push("");
  if (rewritten.length > 0)
    lines.push(
      `Fidelity of the ${rewritten.length} rewrites: with every stretch open, the text kept a mean ${pct(sum(rewritten.map((r) => r.recall ?? 0)) / rewritten.length)} of the original's content words (lowest ${pct(Math.min(...rewritten.map((r) => r.recall ?? 0)))}). Replies under 40 words need no stretches by the guide's own rule and were counted as written.`,
      "",
    );
}
const graded: Graded[] = (() => {
  try {
    return readFileSync(OUT + "coverage.jsonl", "utf8")
      .split("\n")
      .filter(Boolean)
      .map((l) => JSON.parse(l) as Graded);
  } catch {
    return [];
  }
})();
if (graded.length > 0) {
  const replies = graded.length / 2;
  lines.push("## Coverage: does the skim still carry the answer?", "");
  lines.push(
    `For ${replies} of the replayed replies, a blind reader saw only one version and noted every decision, action and result it was told about. A grader listed the original's must-know points (at most eight) and checked both readers' notes against the same list, with the two readers under neutral labels in alternating order. The original is the control: it shows how strict the grader is.`,
    "",
  );
  const credit = (v: string) => (v === "yes" ? 1 : v === "partly" ? 0.5 : 0);
  lines.push(
    "| reader saw | must-know points | caught | partly | missed | coverage, all points | coverage, top three |",
    "|---|---|---|---|---|---|---|",
  );
  for (const version of ["skim", "original"] as const) {
    const set = graded.filter((g) => g.version === version);
    const points = sum(set.map((g) => g.points)),
      yes = sum(set.map((g) => g.yes)),
      partly = sum(set.map((g) => g.partly));
    const top = set.flatMap((g) => (g.verdicts ?? []).slice(0, 3));
    lines.push(
      `| ${version} | ${points} | ${yes} | ${partly} | ${points - yes - partly} | **${pct((yes + partly / 2) / points)}** | **${pct(sum(top.map(credit)) / top.length)}** |`,
    );
  }
  lines.push(
    "",
    'Coverage counts a caught point as 1 and a partly caught one as 0.5. The grader lists points most important first; "top three" scores only those.',
    "",
  );
}

if (native.length > 0) {
  lines.push(
    "## Native: replies written with cc-stretch on, and what the reader opened",
    "",
  );
  lines.push(
    `${native.length} replies: skim ${sum(native.map((r) => r.skim))} of ${sum(native.map((r) => r.full))} full words (${pct(sum(native.map((r) => r.skim)) / sum(native.map((r) => r.full)))}).`,
  );
  if (noted.length > 0)
    lines.push(
      `${noted.length} of them came with a reading note: the reader read ${sum(noted.map((r) => r.read ?? 0))} of ${sum(noted.map((r) => r.full))} words (${pct(sum(noted.map((r) => r.read ?? 0)) / sum(noted.map((r) => r.full)))}).`,
    );
  lines.push("");
}
writeFileSync(
  new URL("./results.md", import.meta.url),
  `${lines.join("\n")}\n`,
);
// One row per replayed reply, counts only, so anyone can recompute the table above.
const csv = [
  "project,session,reply,original_words,skim_words,full_words,content_recall",
  ...replay.map((r) =>
    [
      projectName(r.project),
      (r.session ?? "").slice(0, 8),
      r.turn,
      r.original ?? r.full,
      r.skim,
      r.full,
      (r.recall ?? 1).toFixed(3),
    ].join(","),
  ),
];
writeFileSync(new URL("./results.csv", import.meta.url), `${csv.join("\n")}\n`);
